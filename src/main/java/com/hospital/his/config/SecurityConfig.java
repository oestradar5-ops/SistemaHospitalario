package com.hospital.his.config;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.web.SecurityFilterChain;

@Configuration
public class SecurityConfig {

    @Bean
    public SecurityFilterChain securityFilterChain(
            HttpSecurity http) throws Exception {

        http

                // ==========================================
                // AUTORIZACIÓN DE RUTAS
                // ==========================================

                .authorizeHttpRequests(auth -> auth

                        .requestMatchers(

                                // ==========================================
                                // PORTAL
                                // ==========================================

                                "/",
                                "/portal",

                                // ==========================================
                                // CAJA
                                // ==========================================

                                "/caja/**",
                                "/api/caja/**",

                                // ==========================================
                                // PANEL PRINCIPAL
                                // ==========================================

                                "/panel",
                                "/panel/**",

                                // ==========================================
                                // ENFERMERÍA
                                // ==========================================

                                "/enfermeria/**",
                                "/api/enfermeria/**",

                                // ==========================================
                                // MÉDICO
                                // ==========================================

                                "/medico",
                                "/medico/**",
                                "/api/medico/**",

                                // ==========================================
                                // LABORATORIO - CU-09
                                // ==========================================

                                "/laboratorio/login",
                                "/api/laboratorio/login",

                                // ==========================================
                                // FARMACIA - CU-11
                                // ==========================================

                                "/farmacia",
                                "/farmacia/**",
                                "/api/farmacia/**",

                                // ==========================================
                                // LOGIN PACIENTE
                                // ==========================================

                                "/login",
                                "/logout",

                                // ==========================================
                                // REGISTRO PACIENTE
                                // ==========================================

                                "/registro",

                                // ==========================================
                                // CITAS PACIENTE
                                // ==========================================

                                "/paciente/citas/**",

                                // ==========================================
                                // PAGO PACIENTE
                                // ==========================================

                                "/paciente/pago",
                                "/paciente/pago/**",

                                // ==========================================
                                // ADMINISTRACIÓN
                                // ==========================================

                                "/admin/login",
                                "/admin/usuarios",
                                "/admin/usuarios/**",

                                // ==========================================
                                // RECEPCIÓN
                                // ==========================================

                                "/recepcion/**",
                                "/api/recepcion/**",

                                // ==========================================
                                // API PACIENTE
                                // ==========================================

                                "/api/login",
                                "/api/registro",
                                "/api/verificar-dpi/**",

                                // ==========================================
                                // API CITAS
                                // ==========================================

                                "/api/citas/**",

                                // ==========================================
                                // API PAGOS
                                // ==========================================

                                "/api/pagos/**",

                                // ==========================================
                                // API ADMIN
                                // ==========================================

                                "/api/admin/login",
                                "/api/admin/usuarios/**",

                                // ==========================================
                                // RECURSOS ESTÁTICOS
                                // ==========================================

                                "/css/**",
                                "/js/**",
                                "/img/**",
                                "/images/**",
                                "/error"

                        )
                        .permitAll()

                        // ==========================================
                        // MANTENER COMPORTAMIENTO ACTUAL
                        // ==========================================

                        .anyRequest()
                        .permitAll()
                )

                // ==========================================
                // DESHABILITAR LOGIN PREDETERMINADO
                // ==========================================

                .formLogin(form -> form.disable())

                // ==========================================
                // DESHABILITAR HTTP BASIC
                // ==========================================

                .httpBasic(basic -> basic.disable())

                // ==========================================
                // CONFIGURACIÓN CSRF
                // ==========================================

                .csrf(csrf -> csrf

                        .ignoringRequestMatchers(

                                // ==========================================
                                // LOGIN PACIENTE
                                // ==========================================

                                "/api/login",

                                // ==========================================
                                // LOGIN MÉDICO
                                // ==========================================

                                "/medico/login",

                                // ==========================================
                                // LOGIN LABORATORIO - CU-09
                                // ==========================================

                                "/api/laboratorio/login",

                                // ==========================================
                                // FARMACIA - CU-11
                                // ==========================================

                                "/api/farmacia/login",
                                "/farmacia/api/**",
                                "/farmacia/logout",

                                // ==========================================
                                // REGISTRO
                                // ==========================================

                                "/api/registro",

                                // ==========================================
                                // VERIFICACIÓN DPI
                                // ==========================================

                                "/api/verificar-dpi/**",

                                // ==========================================
                                // CAJA
                                // ==========================================

                                "/api/caja/**",

                                // ==========================================
                                // ADMINISTRACIÓN
                                // ==========================================

                                "/api/admin/login",
                                "/api/admin/usuarios/**",

                                // ==========================================
                                // RECEPCIÓN
                                // ==========================================

                                "/api/recepcion/**",

                                // ==========================================
                                // CITAS
                                // ==========================================

                                "/api/citas/**",

                                // ==========================================
                                // ENFERMERÍA
                                // ==========================================

                                "/api/enfermeria/**",

                                // ==========================================
                                // MÉDICO
                                // ==========================================

                                "/api/medico/**",

                                // ==========================================
                                // CU-12 - AGENDAMIENTO DE SEGUIMIENTO
                                // ==========================================

                                "/medico/citas-seguimiento/api/confirmar",

                                // ==========================================
                                // PAGOS
                                // ==========================================

                                "/api/pagos/**"

                        )
                );

        return http.build();
    }
}